-- =============================================================
-- 个人主页封面图
--
-- 背景：个人主页的封面（近黑瓦片）此前只有一块纯色。用户发的内容里，
-- 头像是唯一能自定义的图，而封面才是「第一眼」的位置。
--
-- 存法与其他图片完全一致：**只存相对路径** `/api/file/objects/...`，
-- 与 avatar 同级同长度。读取时统一过 LocalFileUrls.sanitizeOptional，
-- 非本站地址（旧的外链图床数据）会被当作未设置，页面回落到纯色 + 纹路。
--
-- 为什么单独一列而不是塞进 bio/JSON：它要被 PublicUserProfile 直接下发，
-- 单独一列才能被索引、被后台查询，也不必在每个读路径上解析 JSON。
-- =============================================================

ALTER TABLE u_r_sys_user
    ADD COLUMN cover_image VARCHAR(255) DEFAULT NULL COMMENT '个人主页封面图（相对路径）' AFTER avatar;
